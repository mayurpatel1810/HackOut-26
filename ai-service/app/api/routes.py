@router.get("/health")
def health() -> Dict[str, Any]:
    return state().health()


@router.get("/factors/sources")
def factor_sources() -> Dict[str, Any]:
    st = state()
    by_source: Dict[str, Dict[str, Any]] = {}
    for f in st.repo.factors():
        e = by_source.setdefault(f.source, {
            "source": f.source, "dataset_name": f.dataset_name,
            "dataset_version": f.dataset_version, "publisher": f.publisher,
            "source_url": f.source_url, "geography": f.geography,
            "count": 0, "categories": set(), "years": set()})
        e["count"] += 1
        e["categories"].add(f.category)
        if f.year:
            e["years"].add(f.year)
    out = []
    for e in by_source.values():
        e["categories"] = sorted(e["categories"])
        e["years"] = sorted(e["years"])
        out.append(e)
    return {"sources": out, "total": len(st.repo.factors())}


@router.post("/factors/resolve")
def resolve_factor(req: ResolveRequest) -> Dict[str, Any]:
    st = state()
    try:
        chosen, candidates, notes = st.service.resolver.resolve_energy(
            req.activity_key, req.unit, req.country_code, req.year, req.grid_region)
    except FactorResolutionError as exc:
        raise HTTPException(400, str(exc)) from exc
    return {
        "chosen": chosen.to_dict() if chosen else None,
        "reconciliation": st.service.resolver.reconcile(candidates),
        "candidates": [c.to_dict() for c in candidates],
        "notes": notes,
        "policy": st.repo.policy(
            chosen.factor.category if chosen else "electricity", req.country_code),
    }


@router.post("/ai/extract")
def extract(req: ExtractTextRequest) -> Dict[str, Any]:
    cands = extract_from_text(req.text)
    return {
        "candidates": [c.to_dict() for c in cands],
        "requires_confirmation": [c.to_dict() for c in cands if c.needs_confirmation],
        "note": ("Numbers are read out of your own text by a deterministic parser. "
                 "Nothing here was generated by a language model, and nothing is "
                 "saved until you confirm it."),
    }


@router.post("/ai/extract/rows")
def extract_rows(req: ExtractRowsRequest) -> Dict[str, Any]:
    cands = extract_from_rows(req.rows)
    return {"candidates": [c.to_dict() for c in cands],
            "unreadable": [c.to_dict() for c in cands
                           if c.record_type == "UNREADABLE"]}


@router.post("/ai/analyse")
def analyse(req: AnalyseRequest) -> Dict[str, Any]:
    _, result = _analyse(req)
    return result.summary()


@router.post("/ai/retrieve")
def retrieve(req: AnalyseRequest) -> Dict[str, Any]:
    st, result = _analyse(req)
    rc = RetrievalContext.build(result.ctx, [r for r in result.footprint.calculations],
                                result.hotspots)
    return {"query": rc.to_query(),
            "results": [r.to_dict() for r in result.retrieved],
            "embedding_model": st.embedder.name,
            "degraded": st.embedder.degraded}


@router.post("/ai/rerank")
def rerank(req: AnalyseRequest) -> Dict[str, Any]:
    _, result = _analyse(req)
    return {"ranked": [{"slug": r.intervention.slug,
                        "semantic": round(r.semantic, 4),
                        "hybrid": round(r.hybrid, 4),
                        "reasons": r.reasons} for r in result.retrieved]}



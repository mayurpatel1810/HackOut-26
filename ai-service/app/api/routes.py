@router.post("/ai/evidence")
def evidence(req: CopilotRequest) -> Dict[str, Any]:
    st, result = _analyse(req)
    portfolio = (st.service.optimise(result, req.budget_inr)
                 if req.budget_inr else None)
    scenario = st.service.simulate(result, req.selection) if req.selection else None
    return st.service.evidence_pack(result, req.question, portfolio, scenario)


@router.post("/ai/copilot")
async def copilot(req: CopilotRequest) -> Dict[str, Any]:
    st, result = _analyse(req)
    portfolio = (st.service.optimise(result, req.budget_inr)
                 if req.budget_inr else None)
    scenario = st.service.simulate(result, req.selection) if req.selection else None
    pack = st.service.evidence_pack(result, req.question, portfolio, scenario)
    answer, meta = await LLMClient().explain(pack, req.question)
    return {"answer": answer, "meta": meta,
            "evidence_summary": {
                "leaks": [h.to_dict() for h in result.hotspots[:5]],
                "hard_limits": pack["hard_limits"]},
            "policy": SYSTEM_POLICY}


@router.post("/ai/explain")
async def explain(req: CopilotRequest) -> Dict[str, Any]:
    return await copilot(req)


@router.get("/demo/factory")
def demo_factory() -> Dict[str, Any]:
    ctx, records, history, processes = load_demo()
    return {
        "factory": ctx.__dict__,
        "records": [r.__dict__ for r in records],
        "history": [{"period": h.period, "production": h.production,
                     "values": h.values} for h in history],
        "processes": [p.__dict__ for p in processes],
        "note": ("Only operational inputs are stored for the demo factory. Every "
                 "emission, leak, recommendation, cost and scenario value is "
                 "calculated at runtime from the loaded factor table."),
    }

"""AI service endpoints (Master Spec section 47).

Every route is a thin adapter over app/engines and app/services. No business
rule lives here, which is why the test suite can verify the whole system
without starting a web server.
"""
from __future__ import annotations

import logging
import time
from typing import Any, Dict, List

from fastapi import APIRouter, Depends, HTTPException

from ..copilot.llm import LLMClient
from ..engines.evidence import SYSTEM_POLICY
from ..engines.extraction import extract_from_rows, extract_from_text
from ..engines.factor_resolver import FactorResolutionError
from ..engines.retrieval import RetrievalContext
from ..schemas.api import (AnalyseRequest, CopilotRequest, CurveRequest,
                           ExtractRowsRequest, ExtractTextRequest, OptimiseRequest,
                           ResolveRequest, SimulateRequest)
from ..services.demo_factory import load as load_demo
from .deps import rate_limit, require_service_token, state, to_domain

log = logging.getLogger("ecoforge.api")
router = APIRouter(dependencies=[Depends(rate_limit), Depends(require_service_token)])


def _analyse(req: AnalyseRequest):
    st = state()
    ctx, records, cons, history, processes = to_domain(req)
    t0 = time.perf_counter()
    result = st.service.analyse(ctx, records, view=req.view, constraints=cons,
                                history=history, process_records=processes)
    log.info("analysed factory=%s records=%d in %.0f ms", ctx.factory_id,
             len(records), (time.perf_counter() - t0) * 1000)
    return st, result


